const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const os = require('node:os');
const fs = require('node:fs');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'electroagenda-api-'));
Object.assign(process.env, { DATABASE_URL: '', POSTGRES_URL: '', NEON_DATABASE_URL: '', NODE_ENV: 'test', SQLITE_DB_PATH: path.join(tmp, 'api.db'), DATA_FILE: path.join(tmp, 'missing.json'), AI_GATEWAY_API_KEY: '' });
let authorized = true;
const authPath = require.resolve('../lib/auth.ts');
require.cache[authPath] = { id: authPath, filename: authPath, loaded: true, exports: { isAuthorizedStaff: async () => authorized } };
const { NextRequest } = require('next/server');
const collection = require('../app/api/appointments/route.ts');
const detail = require('../app/api/appointments/[id]/route.ts');
const metrics = require('../app/api/metrics/route.ts');
const req = (url, method = 'GET', body) => new NextRequest(`http://localhost${url}`, { method, ...(body ? { body: JSON.stringify(body), headers: { 'Content-Type': 'application/json' } } : {}) });
test('HTTP workflow records confirmation and arrival, exports KPIs, rejects unauthorized access', async () => {
  authorized = false;
  assert.equal((await collection.GET(req('/api/appointments'))).status, 401);
  assert.equal((await metrics.GET(req('/api/metrics'))).status, 401);
  const response = await collection.POST(req('/api/appointments', 'POST', { clientName: 'Cliente prueba', phone: '0000000000', address: 'Domicilio prueba', propertyType: 'Casa', description: 'Revisión preventiva', preferredSlots: ['2030-11-04T15:00:00Z'] }));
  assert.equal(response.status, 201);
  const { appointment } = await response.json();
  assert.equal(appointment.firstConfirmedAt, null);
  const context = { params: Promise.resolve({ id: appointment.id }) };
  assert.equal((await detail.PATCH(req('/api/appointments/a', 'PATCH', { status: 'Confirmada' }), context)).status, 401);
  authorized = true;
  const confirmed = await detail.PATCH(req('/api/appointments/a', 'PATCH', { expectedRevision: 0, status: 'Confirmada', scheduledAt: '2030-11-04T15:00:00Z', durationMin: 60 }), context);
  assert.equal(confirmed.status, 200);
  const first = (await confirmed.json()).appointment.firstConfirmedAt;
  assert(first);
  assert.equal((await detail.PATCH(req('/api/appointments/a', 'PATCH', { notes: 'Sin versión' }), context)).status, 428);
  assert.equal((await detail.PATCH(req('/api/appointments/a', 'PATCH', { expectedRevision: 0, notes: 'Ficha obsoleta' }), context)).status, 409);
  const changed = await detail.PATCH(req('/api/appointments/a', 'PATCH', { expectedRevision: 1, status: 'Confirmada', scheduledAt: '2030-11-04T16:00:00Z' }), context);
  assert.equal((await changed.json()).appointment.firstConfirmedAt, first);
  const arrived = await detail.PATCH(req('/api/appointments/a', 'PATCH', { expectedRevision: 2, status: 'En servicio' }), context);
  const arrival = (await arrived.json()).appointment;
  assert(arrival.arrivedAt);
  assert.equal(arrival.arrivalScheduledAt, '2030-11-04T16:00:00.000Z');
  assert.equal((await detail.PATCH(req('/api/appointments/a', 'PATCH', { expectedRevision: 3, scheduledAt: '2030-11-04T17:00:00Z' }), context)).status, 400);
  const report = await metrics.GET(req('/api/metrics'));
  const exported = await report.json();
  assert.equal(exported.kpis.scheduling.valid, 1);
  assert.equal(exported.kpis.punctuality.valid, 1);
  assert.equal('clientName' in exported.records[0], false);
  assert.equal((await metrics.GET(req('/api/metrics?from=invalid'))).status, 400);
});

test('stale browser edits and reclassification cannot overwrite newer notes', async () => {
  const reclassify = require('../app/api/appointments/[id]/reclassify/route.ts');
  const { appointments } = await (await collection.GET(req('/api/appointments'))).json();
  const original = appointments[0];
  const context = { params: Promise.resolve({ id: original.id }) };
  const saved = await detail.PATCH(req('/api/appointments/a', 'PATCH', { expectedRevision: original.revision, notes: 'Observación verificada' }), context);
  assert.equal(saved.status, 200);
  const latest = (await saved.json()).appointment;
  assert.equal(latest.notes, 'Observación verificada');
  assert.equal(latest.revision, original.revision + 1);
  const stale = await detail.PATCH(req('/api/appointments/a', 'PATCH', { expectedRevision: original.revision, notes: 'Nota vieja' }), context);
  assert.equal(stale.status, 409);
  assert.equal((await reclassify.POST(req('/api/appointments/a/reclassify', 'POST', { expectedRevision: original.revision }), context)).status, 409);
  authorized = false;
  assert.equal((await reclassify.POST(req('/api/appointments/a/reclassify', 'POST', { expectedRevision: latest.revision }), context)).status, 401);
  authorized = true;
  const reclassified = await reclassify.POST(req('/api/appointments/a/reclassify', 'POST', { expectedRevision: latest.revision }), context);
  assert.equal(reclassified.status, 200);
  assert.equal((await reclassified.json()).appointment.notes, latest.notes);
});
